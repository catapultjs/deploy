desc('Checks the Quadlet files and what Quadlet needs on the server')
task('quadlet:check', async ({ host, logger }: TaskContext) => {
  await checkQuadlet(host, logger)
})

desc('Renders the Quadlet files of the project into the release')
task('quadlet:render', async ({ host, logger, release, paths }: TaskContext) => {
  const dir = sourceDir()
  const values: RenderValues = {
    image: releaseRef(release),
    release,
    release_path: paths.release,
    shared_path: paths.shared,
    base_path: host.deployPath,
    project: project(),
  }
  const files = localFiles()
  const output = `${paths.release}/${RENDERED_DIR}`
  const script = ['set -e', 'umask 077', `mkdir -p ${q(output)}`]
  let usesImage = false
  for (const file of files) {
    const content = render(file, readFileSync(join(dir, file.name), 'utf8'), values)
    if (content.includes(values.image)) usesImage = true
    if (
      (file.kind === 'container' || file.kind === 'pod') &&
      !/^\s*\[Install\]\s*$/m.test(content) &&
      // A oneshot unit (e.g. a migration) is usually pulled in by its dependents.
      !/^\s*Type\s*=\s*oneshot\s*$/m.test(content)
    ) {
      logger.warning(`${file.name} has no [Install] section: it will not start at boot`, {
        prefix: host.name,
      })
    }
    script.push(`printf '%s' ${q(content)} > ${q(`${output}/${file.name}`)}`)
  }
  if (!usesImage) {
    logger.warning(`no unit uses the release image: set Image={{image}} in a .container file`, {
      prefix: host.name,
    })
  }
  await ssh(host, script.join('\n'))

  const data: QuadletData = { files: files.map((file) => file.name) }
  rendered.set(`${host.name}|${release}`, data)
  setManifestExtra(host.name, release, 'quadlet', data)
})

desc('Validates the rendered Quadlet files with the Quadlet generator')
task('quadlet:validate', async ({ host, logger, release, paths }: TaskContext) => {
  const facts = await hostFacts(host, logger)
  if (!generators.has(host.name)) await checkQuadlet(host, logger)
  const generator = generators.get(host.name) ?? 'quadlet'
  const dir = `${paths.release}/${RENDERED_DIR}`
  try {
    await ssh(
      host,
      `set -e\nQUADLET_UNIT_DIRS=${q(dir)} ${q(generator)} -dryrun${facts.rootless ? ' -user' : ''} >/dev/null`
    )
  } catch (error) {
    const output = failureOutput(error)
      .split('\n')
      .filter((line) => !/Loading source unit file/.test(line))
      .map((line) => line.replace(/^quadlet-generator\[\d+\]: /, ''))
      .join('\n')
    throw new Error(`[${host.name}] invalid Quadlet files in release ${release}: ${output}`, {
      cause: error,
    })
  }
})

desc('Installs the units of the release, restarts the changed ones and waits until they are ready')
task('quadlet:up', async (ctx: TaskContext) => {
  const target = await loadTarget(ctx.host, ctx.logger, ctx.release, ctx.paths.release)
  await up(target, ctx.logger, verbosity(ctx))
})

desc('Starts the units of the project')
task('quadlet:start', async (ctx: TaskContext) => {
  const target = await loadTarget(ctx.host, ctx.logger, ctx.release, ctx.paths.release)
  const units = serviceUnits(target.files)
  await systemd(
    target,
    `set -e\n${resetFailed(target)}\n${systemctl(target.facts)} start ${units.map(q).join(' ')}`,
    'systemctl start'
  )
  await wait(target, ctx.logger, verbosity(ctx))
})

desc('Stops the units of the project')
task('quadlet:stop', async ({ host, logger, release, paths }: TaskContext) => {
  const target = await loadTarget(host, logger, release, paths.release)
  const units = serviceUnits(target.files)
  await systemd(
    target,
    `set -e\n${systemctl(target.facts)} stop ${units.map(q).join(' ')}`,
    'systemctl stop'
  )
})

desc('Restarts the units of the project and waits until they are ready')
task('quadlet:restart', async (ctx: TaskContext) => {
  const target = await loadTarget(ctx.host, ctx.logger, ctx.release, ctx.paths.release)
  const units = serviceUnits(target.files)
  await systemd(
    target,
    `set -e\n${resetFailed(target)}\n${systemctl(target.facts)} restart ${units.map(q).join(' ')}`,
    'systemctl restart'
  )
  await wait(target, ctx.logger, verbosity(ctx))
})

desc('Stops the units and removes the Quadlet files of the project (volumes are kept)')
task('quadlet:uninstall', async ({ host, logger, release, paths }: TaskContext) => {
  const target = await loadTarget(host, logger, release, paths.release)
  const ctl = systemctl(target.facts)
  await systemd(
    target,
    `set -e
${ctl} stop ${target.files.map(unitName).map(q).join(' ')} >/dev/null 2>&1 || true
rm -rf ${installDir(target.facts)}
${ctl} daemon-reload`,
    'uninstall'
  )
})

desc('Displays the journal of the units of the project')
task('quadlet:logs', async ({ host, logger, release, paths }: TaskContext) => {
  const target = await loadTarget(host, logger, release, paths.release)
  const units = serviceUnits(target.files).map((unit) => `-u ${q(unit)}`)
  const { stdout } = await ssh(
    host,
    `set +e\n${journalctl(target.facts)} ${units.join(' ')} -n ${q(String(logLines()))} --no-pager 2>&1`
  )
  logger.log(stdout.trim())
})

desc('Displays the status of the units of the project')
task('quadlet:status', async ({ host, logger, release, paths }: TaskContext) => {
  const target = await loadTarget(host, logger, release, paths.release)
  const { stdout } = await ssh(
    host,
    `set +e\n${systemctl(target.facts)} status ${serviceUnits(target.files).map(q).join(' ')} --no-pager 2>&1`
  )
  logger.log(stdout.trim())
})

