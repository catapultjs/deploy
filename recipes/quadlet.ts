onSetup(async (_ctx, host, logger) => {
  await checkQuadlet(host, logger)
})

onStatus(async (ctx, host, logger) => {
  try {
    const { current } = getPaths(host.deployPath, ctx.release)
    const target = await loadTarget(host, logger, 'current', current)
    const states = await unitStates(target, serviceUnits(target.files))
    return Object.fromEntries(
      [...states].map(([unit, state]) => [`quadlet:${unit}`, `${state.active}/${state.sub}`])
    )
  } catch {
    return { quadlet: 'unavailable' }
  }
})

onBeforeRollback(async (ctx, host, logger) => {
  const paths = getPaths(host.deployPath, ctx.release)
  const target = await loadTarget(host, logger, ctx.release, paths.release)
  const source = `${paths.release}/${RENDERED_DIR}`
  try {
    await ssh(
      host,
      `set -e\n${target.files.map((file) => `[ -f ${q(`${source}/${file.name}`)} ]`).join('\n')}`
    )
  } catch {
    throw new Error(`[${host.name}] release ${ctx.release} is missing its Quadlet files`)
  }
})

onRollback(async (ctx, host, logger) => {
  const paths = getPaths(host.deployPath, ctx.release)
  const target = await loadTarget(host, logger, ctx.release, paths.release)
  await up(target, logger, ctx.config.verbose ?? Verbose.SILENT)
})

