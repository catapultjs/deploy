function fail(message: string): never {
  throw new Error(message)
}

function sourceDir(): string {
  const value = get<string>('quadlet_path', 'quadlet')
  if (typeof value !== 'string' || !value.trim()) fail('quadlet_path must be a non-empty string')
  return resolve(process.cwd(), value)
}

function seconds(key: string, fallback: number): number {
  const value = Number(get<number>(key, fallback))
  if (!Number.isFinite(value) || value <= 0) fail(`${key} must be a positive number of seconds`)
  return value
}

function logLines(): number {
  const value = Number(get<number>('quadlet_logs_lines', 100))
  return Number.isFinite(value) && value > 0 ? Math.floor(value) : 100
}

export function quadletFile(name: string): QuadletFile {
  const extension = extname(name).slice(1)
  const base = name.slice(0, -(extension.length + 1))
  if (extension in UNSUPPORTED)
    fail(`${name}: .${extension} files are not supported, ${UNSUPPORTED[extension]}`)
  if (!(KINDS as readonly string[]).includes(extension)) {
    fail(`${name}: unsupported file, expected ${KINDS.map((kind) => `.${kind}`).join(', ')}`)
  }
  if (!base || !NAME_PATTERN.test(base)) fail(`${name}: invalid unit name`)
  return { name, kind: extension as Kind, base }
}

/** Quadlet files of the project, in `quadlet_path`. Hidden files are ignored. */
export function localFiles(): QuadletFile[] {
  const dir = sourceDir()
  let entries: string[]
  try {
    entries = readdirSync(dir)
  } catch {
    fail(`quadlet_path not found: ${dir}`)
  }
  const files = entries
    .filter((entry) => !entry.startsWith('.'))
    .sort()
    .map((entry) => {
      if (!statSync(join(dir, entry)).isFile()) {
        fail(`quadlet_path must only contain files: ${entry} is a directory`)
      }
      return quadletFile(entry)
    })
  if (!files.some((file) => file.kind === 'container')) {
    fail(`quadlet_path must contain at least one .container file: ${dir}`)
  }
  return files
}

/** systemd service generated by Quadlet for a file. */
export function unitName(file: QuadletFile): string {
  return file.kind === 'container' ? `${file.base}.service` : `${file.base}-${file.kind}.service`
}

/** Units that run containers: the ones started, stopped and watched. */
function serviceUnits(files: QuadletFile[]): string[] {
  return files.filter((f) => f.kind === 'container' || f.kind === 'pod').map(unitName)
}

export interface RenderValues {
  image: string
  release: string
  release_path: string
  shared_path: string
  base_path: string
  project: string
}

/**
 * Replaces `{{placeholders}}` and labels containers with the project and service, so
 * Catapult finds them. The release is not added as a label: a unit whose file does not
 * change (an external image) is not restarted.
 */
export function render(file: QuadletFile, source: string, values: RenderValues): string {
  const lines = source.replace(PLACEHOLDER, (_match, key: string) => {
    if (!(key in values)) fail(`${file.name}: unknown placeholder {{${key}}}`)
    return values[key as keyof RenderValues]
  })
  const content = lines.split('\n')
  if (content.some((line) => /^\s*ServiceName\s*=/.test(line))) {
    fail(`${file.name}: ServiceName= is not supported, Catapult derives unit names from file names`)
  }
  if (file.kind !== 'container') return lines

  if (content.some((line) => /^\s*Label\s*=\s*"?com\.catapultjs\./.test(line))) {
    fail(`${file.name}: labels with the com.catapultjs. prefix are reserved`)
  }
  const repository = `localhost/${imageName()}`
  for (const line of content) {
    const match = /^\s*Image\s*=\s*(\S+)\s*$/.exec(line)
    if (match && match[1].startsWith(`${repository}:`) && match[1] !== values.image) {
      fail(`${file.name}: Image=${match[1]} is not the release image, use Image={{image}}`)
    }
  }
  const section = content.findIndex((line) => line.trim() === '[Container]')
  if (section === -1) fail(`${file.name}: missing [Container] section`)
  content.splice(
    section + 1,
    0,
    `Label=${LABEL_PROJECT}=${values.project}`,
    `Label=${LABEL_SERVICE}=${file.base}`
  )
  return content.join('\n')
}

