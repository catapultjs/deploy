const KINDS = ['container', 'network', 'volume', 'pod'] as const
type Kind = (typeof KINDS)[number]
const UNSUPPORTED: Record<string, string> = {
  build: 'Catapult builds the image, locally or on the servers',
  image: 'images are transferred by Catapult',
  kube: 'Kubernetes YAML is not supported',
}
const NAME_PATTERN = /^[a-zA-Z0-9][a-zA-Z0-9_.-]*$/
const PLACEHOLDER = /\{\{\s*([a-z_]+)\s*\}\}/g
const RENDERED_DIR = 'quadlet'
const LABEL_PROJECT = 'com.catapultjs.project'
const LABEL_SERVICE = 'com.catapultjs.service'
const STABLE_CHECKS = 2

interface QuadletFile {
  name: string
  kind: Kind
  base: string
}

interface QuadletData {
  files: string[]
}

interface Target {
  host: Host
  facts: RemoteFacts
  release: string
  path: string
  files: QuadletFile[]
}

