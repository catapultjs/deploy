function systemctl(facts: RemoteFacts): string {
  return facts.rootless ? 'systemctl --user' : 'systemctl'
}

function journalctl(facts: RemoteFacts): string {
  return facts.rootless ? 'journalctl --user' : 'journalctl'
}

/** Shell expression of the directory holding the units of the project. */
function installDir(facts: RemoteFacts): string {
  return facts.rootless
    ? `"\${XDG_CONFIG_HOME:-$HOME/.config}/containers/systemd/"${q(project())}`
    : q(`/etc/containers/systemd/${project()}`)
}

function verbosity(ctx: { config: TaskContext['config'] }): number {
  return ctx.config.verbose ?? Verbose.SILENT
}

function parse(stdout: string): {
  values: Record<string, string>
  lists: Record<string, string[]>
} {
  const values: Record<string, string> = {}
  const lists: Record<string, string[]> = {}
  for (const line of stdout.split('\n')) {
    const index = line.indexOf('=')
    if (index <= 0) continue
    const key = line.slice(0, index)
    const value = line.slice(index + 1).trim()
    values[key] = value
    ;(lists[key] ??= []).push(value)
  }
  return { values, lists }
}

const generators = new Map<string, string>()

/**
 * Checks what Quadlet needs on the server: Podman, systemd, a reachable service
 * manager, cgroups v2, linger for rootless, and no unit of the same name installed by
 * another project. Never installs or changes anything.
 */
async function checkQuadlet(host: Host, logger: CatapultLogger): Promise<RemoteFacts> {
  const facts = await hostFacts(host, logger)
  if (facts.engine !== 'podman') {
    fail(`[${host.name}] Quadlet requires Podman, found ${facts.engine}`)
  }
  const names = localFiles().map((file) => file.name)
  const { stdout } = await ssh(
    host,
    `set +e
for p in "$(command -v quadlet 2>/dev/null)" /usr/libexec/podman/quadlet /usr/lib/podman/quadlet; do
  if [ -n "$p" ] && [ -x "$p" ]; then echo "generator=$p"; break; fi
done
command -v systemctl >/dev/null 2>&1 || { echo systemd=no; exit 0; }
${systemctl(facts)} show-environment >/dev/null 2>&1 && echo manager=yes
echo "cgroup=$(stat -fc %T /sys/fs/cgroup 2>/dev/null)"
dir=${installDir(facts)}
base=$(dirname "$dir")
if [ -d "$base" ]; then
  for name in ${names.map(q).join(' ')}; do
    find "$base" -name "$name" -not -path "$dir/*" 2>/dev/null | sed 's/^/conflict=/'
  done
fi`
  )
  const { values, lists } = parse(stdout)
  const mode = facts.rootless ? 'rootless' : 'rootful'
  if (values.systemd === 'no') fail(`[${host.name}] Quadlet requires systemd`)
  if (!values.generator) {
    fail(`[${host.name}] Quadlet generator not found: Podman 4.4 or later is required`)
  }
  if (facts.rootless && facts.linger === 'no') {
    fail(
      `[${host.name}] linger is disabled: rootless units stop when the SSH session ends. Run \`sudo loginctl enable-linger <user>\` on the server`
    )
  }
  if (values.manager !== 'yes') {
    fail(
      `[${host.name}] the systemd ${facts.rootless ? 'user ' : ''}manager is not reachable over SSH (${mode})`
    )
  }
  if (values.cgroup && values.cgroup !== 'cgroup2fs') {
    const message = `cgroups v2 is not enabled (found ${values.cgroup})`
    if (facts.rootless) fail(`[${host.name}] ${message}: rootless Quadlet requires it`)
    logger.warning(message, { prefix: host.name })
  }
  if (lists.conflict?.length) {
    fail(
      `[${host.name}] units with the same name are installed outside this project: ${lists.conflict.join(', ')}`
    )
  }
  generators.set(host.name, values.generator)
  return facts
}

const rendered = new Map<string, QuadletData>()

/** Quadlet files of a release: from this deployment, else from its manifest. */
async function loadTarget(
  host: Host,
  logger: CatapultLogger,
  release: string,
  path: string
): Promise<Target> {
  const facts = await hostFacts(host, logger)
  let data = rendered.get(`${host.name}|${release}`)
  if (!data) {
    const manifest = await readManifest(host, path)
    data = manifest?.quadlet as QuadletData | undefined
  }
  if (!data?.files?.length) {
    throw new Error(`[${host.name}] release ${release} has no Quadlet files`)
  }
  return { host, facts, release, path, files: data.files.map(quadletFile) }
}

async function systemd(target: Target, script: string, action: string) {
  try {
    return await ssh(target.host, script)
  } catch (error) {
    throw new Error(
      `[${target.host.name}] ${action} failed: ${failureOutput(error) || (error as Error).message}. See \`cata task quadlet:logs\``,
      { cause: error }
    )
  }
}

/**
 * Clears the failed state and start limit of the service units: after a crash loop,
 * systemd refuses to start them again ("start of the service was attempted too often").
 */
function resetFailed(target: Target): string {
  const units = serviceUnits(target.files).map(q).join(' ')
  return `${systemctl(target.facts)} reset-failed ${units} >/dev/null 2>&1 || true`
}

interface UnitState {
  active: string
  sub: string
  restarts: number
}

async function unitStates(target: Target, units: string[]): Promise<Map<string, UnitState>> {
  const { stdout } = await ssh(
    target.host,
    `set -e\n${systemctl(target.facts)} show --property=Id,ActiveState,SubState,NRestarts ${units.map(q).join(' ')}`
  )
  const states = new Map<string, UnitState>()
  for (const block of stdout.split(/\n\s*\n/)) {
    const { values } = parse(block)
    if (!values.Id) continue
    states.set(values.Id, {
      active: values.ActiveState ?? 'unknown',
      sub: values.SubState ?? '',
      restarts: Number.parseInt(values.NRestarts ?? '', 10) || 0,
    })
  }
  return states
}

/**
 * Waits until every service unit is active, without restarting repeatedly (a crash
 * loop driven by `Restart=`), then until the containers run and are healthy. Checks the
 * units once more afterwards: a container that exited is removed by Quadlet.
 */
async function wait(target: Target, logger: CatapultLogger, verbose: number) {
  const units = serviceUnits(target.files)
  const timeoutSeconds = seconds('quadlet_wait_timeout', 60)
  const deadline = Date.now() + timeoutSeconds * 1000
  const first = new Map<string, number>()
  const hint = 'See `cata task quadlet:logs`'
  const check = async (final: boolean) => {
    const states = await unitStates(target, units)
    const failed: string[] = []
    const pending: string[] = []
    const looping: string[] = []
    for (const unit of units) {
      const state = states.get(unit) ?? { active: 'unknown', sub: '', restarts: 0 }
      if (!first.has(unit)) first.set(unit, state.restarts)
      if (state.restarts - (first.get(unit) ?? 0) >= STABLE_CHECKS) looping.push(unit)
      else if (state.active === 'active') continue
      else if (!final && ['activating', 'reloading'].includes(state.active)) pending.push(unit)
      else failed.push(`${unit} (${state.active}${state.sub ? `/${state.sub}` : ''})`)
    }
    if (looping.length) {
      fail(
        `[${target.host.name}] units restarted while starting (crash loop): ${looping.join(', ')}. ${hint}`
      )
    }
    if (failed.length) fail(`[${target.host.name}] units not active: ${failed.join(', ')}. ${hint}`)
    return pending
  }

  while (true) {
    const pending = await check(false)
    if (!pending.length) break
    if (Date.now() >= deadline) {
      fail(`[${target.host.name}] units not active after ${timeoutSeconds}s: ${pending.join(', ')}`)
    }
    await sleep(2_000)
  }

  const services = target.files.filter((file) => file.kind === 'container')
  await waitReady({
    host: target.host,
    facts: target.facts,
    filterSets: services.map((file) => [
      `${LABEL_PROJECT}=${project()}`,
      `${LABEL_SERVICE}=${file.base}`,
    ]),
    timeoutSeconds,
    logger,
    verbose: Verbose.SILENT,
    logsTask: 'quadlet:logs',
  })
  await check(true)
  if (verbose >= Verbose.NORMAL) logger.step(target.host.name, `${units.length} unit(s) active`)
}

/**
 * Installs the Quadlet files of a release in the project directory: removes the units
 * no longer in the project, copies the changed files, reloads systemd, restarts the
 * changed units and starts the others, then waits until they are ready.
 */
async function up(target: Target, logger: CatapultLogger, verbose: number) {
  const { facts } = target
  const source = `${target.path}/${RENDERED_DIR}`
  const names = target.files.map((file) => file.name)
  const { stdout } = await ssh(
    target.host,
    `set -e
dir=${installDir(facts)}
mkdir -p "$dir"
for f in "$dir"/*; do [ -f "$f" ] && echo "installed=$(basename "$f")"; done
for n in ${names.map(q).join(' ')}; do cmp -s ${q(source)}/"$n" "$dir/$n" || echo "changed=$n"; done
true`
  )
  const { lists } = parse(stdout)
  const changed = (lists.changed ?? []).map(quadletFile)
  const removed = (lists.installed ?? [])
    .filter((name) => !names.includes(name))
    .flatMap((name) => {
      try {
        return [quadletFile(name)]
      } catch {
        return []
      }
    })

  const ctl = systemctl(facts)
  const script = ['set -e', `dir=${installDir(facts)}`]
  if (removed.length) {
    script.push(`${ctl} stop ${removed.map(unitName).map(q).join(' ')} >/dev/null 2>&1 || true`)
    script.push(...removed.map((file) => `rm -f "$dir"/${q(file.name)}`))
  }
  for (const file of changed) {
    script.push(
      `cp ${q(`${source}/${file.name}`)} "$dir"/${q(file.name)}`,
      `chmod 600 "$dir"/${q(file.name)}`
    )
  }
  script.push(`${ctl} daemon-reload`, resetFailed(target))
  if (removed.length) {
    // A unit stopped by SIGTERM may end as failed (exit code 143): leave no trace of it.
    script.push(
      `${ctl} reset-failed ${removed.map(unitName).map(q).join(' ')} >/dev/null 2>&1 || true`
    )
  }
  if (changed.length) script.push(`${ctl} restart ${changed.map(unitName).map(q).join(' ')}`)
  script.push(`${ctl} start ${serviceUnits(target.files).map(q).join(' ')}`)

  if (verbose >= Verbose.NORMAL) {
    const restarted = changed.map(unitName)
    logger.step(
      target.host.name,
      restarted.length ? `restart ${restarted.join(', ')}` : 'no unit changed'
    )
    if (removed.length) logger.step(target.host.name, `remove ${removed.map(unitName).join(', ')}`)
  }
  await systemd(target, script.join('\n'), 'systemctl')
  await wait(target, logger, verbose)
}

